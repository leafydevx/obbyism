def _findings_to_html(findings):
    if not findings:
        return '<p style="color: var(--muted);">No findings recorded.</p>'
    html = ""
    order = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}
    for f in sorted(findings, key=lambda x: order.get(x.get("severity", "info"), 5)):
        sev = f.get("severity", "info")
        title = f.get("title", "")
        detail = f.get("detail", "")
        module = f.get("module", "")
        html += f'<div class="finding {sev}">'
        html += f'<span class="sev">{sev}</span> {title}'
        if module:
            html += f' <span style="color: var(--muted); font-size: 0.75rem;">({module})</span>'
        if detail:
            html += f'<div class="detail">{detail}</div>'
        html += "</div>\n"
    return html


def _modules_to_html(results):
    if not results:
        return '<p style="color: var(--muted);">No module data.</p>'
    html = ""
    for mod_name, entry in results.items():
        data = entry.get("data", {})
        ts = entry.get("timestamp", "")
        html += f"<h3 style='color: var(--text); margin-top: 1.5rem;'>{mod_name}</h3>"
        html += f'<p style="color: var(--muted); font-size: 0.75rem;">Run at: {ts}</p>'
        html += f"<pre>{json.dumps(data, indent=2, default=str)}</pre>"
    return html


@ModuleRegistry.register
class ReportGenerator(BaseModule):
    name = "report"
    description = "Assessment Report Generator"
    category = "report"

    def run(self, target, **kwargs):
        fmt = kwargs.get("format", "html")
        output_path = kwargs.get("output")

        summary = self.session.summary()
        counts = summary["severity_counts"]

        if fmt == "json":
            report = {
                "target": self.session.target,
                "session": self.session.name,
                "generated": datetime.datetime.now(datetime.timezone.utc).isoformat(),
                "summary": summary,
                "findings": self.session.findings,
                "results": self.session.results,
            }
            content = json.dumps(report, indent=2, default=str)
            ext = ".json"

        elif fmt == "txt":
            lines = [
                "=" * 60,
                "OBBYISM SECURITY ASSESSMENT REPORT",
                "=" * 60,
                f"Target:  {self.session.target}",
                f"Session: {self.session.name}",
                f"Date:    {datetime.datetime.now(datetime.timezone.utc).isoformat()}",
                "",
                "SUMMARY",
                "-" * 40,
                f"  Critical: {counts.get('critical', 0)}",
                f"  High:     {counts.get('high', 0)}",
                f"  Medium:   {counts.get('medium', 0)}",
                f"  Low:      {counts.get('low', 0)}",
                f"  Info:     {counts.get('info', 0)}",
                "",
                "FINDINGS",
                "-" * 40,
            ]
            for f in self.session.findings:
                lines.append(f"  [{f['severity'].upper()}] {f['title']}")
                if f.get("detail"):
                    lines.append(f"    {f['detail']}")
            content = "\n".join(lines)
            ext = ".txt"

        else:
            content = HTML_TEMPLATE.format(
                target=self.session.target,
                timestamp=datetime.datetime.now(datetime.timezone.utc).isoformat(),
                session_name=self.session.name,
                critical=counts.get("critical", 0),
                high=counts.get("high", 0),
                medium=counts.get("medium", 0),
                low=counts.get("low", 0),
                findings_html=_findings_to_html(self.session.findings),
                modules_html=_modules_to_html(self.session.results),
            )
            ext = ".html"

        if not output_path:
            output_path = (
                self.session.config.reports_dir
                / f"{self.session.name}_report{ext}"
            )

        output_path = Path(output_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, "w") as f:
            f.write(content)

        self.output.success(f"Report saved to {output_path}")
        return {"path": str(output_path), "format": fmt}
